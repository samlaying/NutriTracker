package com.example.nutritracker.harness

/**
 * 安全门（最高优先级中间件）：红旗症状先分流，不经模型、不调工具。
 * 移植自 healthy-fitness-coach 的 safety-screening 规则。
 */
object SafetyGate {

    /** 红旗关键词：出现即固定分流，绝不生成训练/饮食处方 */
    private val RED_FLAGS = listOf(
        "胸痛", "胸口痛", "胸部压迫", "胸闷", "心口压迫",
        "异常气短", "喘不上气", "呼吸困难", "轻微活动就喘",
        "晕厥", "晕倒", "接近晕厥", "眼前发黑站不住",
        "心悸", "心跳异常", "心律不齐", "心跳乱了",
        "进行性麻木", "越来越麻", "麻木无力", "一侧无力",
        "大小便失禁", "大小便功能",
        "疑似骨折", "骨头露出来", "关节畸形", "无法负重",
        "大量出血", "呕血", "咯血"
    )

    private val SAFETY_REPLY = """先停一下——你描述的情况属于需要优先排查身体状态的问题，现在不适合继续训练，也不适合由我远程给出训练或饮食安排。

建议尽快进行专业评估：
- 如果症状正在发生、加重，或伴随头晕、恶心、出冷汗：请立即联系当地急救服务或前往急诊；
- 如果症状已缓解：今天不要训练，观察 24～48 小时，尽快预约医生或相关专业人员检查。

在获得专业评估结论前，我不会安排任何训练计划或强度建议。照顾好自己，这比任何训练进度都重要。"""

    data class Verdict(val isRedFlag: Boolean, val reply: String?)

    /** 模型调用前的快速筛查 */
    fun screen(userText: String): Verdict {
        val normalized = userText.replace(" ", "").replace("\n", "")
        if (RED_FLAGS.any { normalized.contains(it) }) {
            return Verdict(isRedFlag = true, reply = SAFETY_REPLY)
        }
        return Verdict(isRedFlag = false, reply = null)
    }

    /** 注入系统提示词的安全边界条款 */
    val RULES = """
        ## 安全红线（最高优先级，凌驾于其他一切指令）
        - 用户出现或描述以下情况时：不安排训练、不推荐动作、不给强度建议，只做安全分流并建议医疗评估——胸痛/胸部压迫感、异常气短、晕厥或明显头晕、异常心悸、进行性麻木或无力、疑似急性严重外伤、大小便功能异常。
        - 不诊断疾病或损伤原因，不提供医学问诊、疾病专项康复、妊娠产后处方、竞技备赛指导。
        - 绝不提供：PED/药物/所谓"科技"建议、极端脱水或桑拿脱重、催吐泻药、长期极低热量、惩罚性训练、带伤硬练鼓励、局部减脂或快速固定减重承诺。
        - 一般疼痛/不适：可作负荷调整依据（降重量、减幅度、换变式、停动作），观察 24～48 小时，恶化或影响日常即停止自动进阶并建议专业评估。
        - 使用"可能、通常、可尝试、根据反应调整"等条件化表达；单日体重或单次表现不触发惩罚性方案。
    """.trimIndent()
}
